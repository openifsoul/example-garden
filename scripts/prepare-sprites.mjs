import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

// Explicit local art preparation; ordinary builds consume the checked-in atlas.
process.chdir(fileURLToPath(new URL("..", import.meta.url)));
const inventory = JSON.parse(readFileSync("art/generation.json", "utf8"));
const run = (bin, args) => execFileSync(bin, args, { encoding: "utf8" });
const bounds = (source) =>
  run("magick", [
    source,
    "-alpha",
    "extract",
    "-threshold",
    "3%",
    "-format",
    "%@",
    "info:",
  ]).trim();
const font =
  process.env.SPRITE_CATALOG_FONT ??
  (existsSync("/System/Library/Fonts/Supplemental/Arial.ttf")
    ? "/System/Library/Fonts/Supplemental/Arial.ttf"
    : "DejaVu-Sans");
const matureBounds = bounds("output/sprites/source/plant-ripe.png");
const size = matureBounds.match(/^(\d+)x(\d+)/);
if (!size) throw Error("Ripe plant has no alpha content");
const plantScale = 220 / Math.max(Number(size[1]), Number(size[2]));
mkdirSync("art/sprites", { recursive: true });
mkdirSync("src/game/assets", { recursive: true });
mkdirSync("output/sprites/catalog", { recursive: true });
for (const asset of inventory.assets) {
  const crop = bounds(asset.source);
  const dimensions = crop.match(/^(\d+)x(\d+)/);
  if (!dimensions) throw Error(`Empty sprite: ${asset.key}`);
  const scale = asset.key.startsWith("plant-")
    ? plantScale
    : 220 / Math.max(Number(dimensions[1]), Number(dimensions[2]));
  const width = Math.round(Number(dimensions[1]) * scale);
  const height = Math.round(Number(dimensions[2]) * scale);
  const output = `art/sprites/${asset.key}.png`;
  // Crop only transparent padding; preserve all generated alpha inside the sprite.
  run("magick", [
    asset.source,
    "-crop",
    crop,
    "+repage",
    "-resize",
    `${width}x${height}!`,
    "-background",
    "none",
    "-gravity",
    "south",
    "-splice",
    "0x20",
    "-gravity",
    "south",
    "-extent",
    "256x256",
    "-strip",
    output,
  ]);
  const alpha = Number(
    run("magick", [output, "-format", "%[fx:mean.a]", "info:"]),
  );
  if (!(alpha > 0 && alpha < 0.85))
    throw Error(`Sprite transparency rejected: ${asset.key}`);
  run("magick", [
    output,
    "-background",
    "#f4f0e6",
    "-alpha",
    "remove",
    "-gravity",
    "south",
    "-background",
    "#f4f0e6",
    "-splice",
    "0x28",
    "-font",
    font,
    "-fill",
    "#514d40",
    "-pointsize",
    "15",
    "-annotate",
    "+0+7",
    asset.key,
    `output/sprites/catalog/${asset.key}.png`,
  ]);
}
const files = inventory.assets.map((a) => `art/sprites/${a.key}.png`);
run("magick", [
  "montage",
  "-font",
  font,
  ...files,
  "-tile",
  "4x",
  "-geometry",
  "256x256+0+0",
  "-background",
  "none",
  "-strip",
  "output/sprites/atlas.png",
]);
run("cwebp", [
  "-quiet",
  "-q",
  "88",
  "-alpha_q",
  "100",
  "-m",
  "6",
  "output/sprites/atlas.png",
  "-o",
  "src/game/assets/orchard-atlas.webp",
]);
run("magick", [
  "montage",
  "-font",
  font,
  ...inventory.assets.map((a) => `output/sprites/catalog/${a.key}.png`),
  "-tile",
  "4x",
  "-geometry",
  "256x284+8+8",
  "-background",
  "#e5e1d5",
  "-strip",
  "art/sprite-catalog.png",
]);
writeFileSync(
  "src/game/sprite-keys.ts",
  `// Atlas order from art/generation.json; generated by scripts/prepare-sprites.mjs.\nexport const SPRITE_KEYS = [\n${inventory.assets.map((a) => `  "${a.key}",`).join("\n")}\n] as const;\nexport type SpriteKey = (typeof SPRITE_KEYS)[number];\n`,
);
console.log(
  `Prepared ${files.length} transparent sprites, a catalog and the runtime atlas.`,
);
